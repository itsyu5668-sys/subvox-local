#!/usr/bin/env python3
"""Regenerate MODELS.md from the actual files in models/.

Usage: python3 scripts/model_inventory.py
Prints size + sha256 for every file. Do NOT hand-edit MODELS.md —
re-run this script after downloads finish.
"""
import hashlib
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
MODELS = os.path.join(ROOT, "models")

CATALOG = [
    ("models/vsr/model.json", "Amanvir/LRS3_V_WER19.1", "Auto-AVSR config"),
    ("models/vsr/model.pth", "Amanvir/LRS3_V_WER19.1", "Auto-AVSR visual-only weights, LRS3 19.1% WER"),
    ("models/lm/model.json", "Amanvir/lm_en_subword", "Subword LM config"),
    ("models/lm/model.pth", "Amanvir/lm_en_subword", "Subword RNN LM weights"),
    ("models/lm/unigram5000.model", "mpc001/auto_avsr (GitHub)", "SentencePiece tokenizer"),
    ("models/face_landmarker.task", "Google MediaPipe", "FaceLandmarker float16"),
    ("models/av/config.json", "nguyenvulebinh/auto_avsr_av_trlrwlrs2lrs3vox2avsp_base", "AV model config"),
    ("models/av/model.safetensors", "nguyenvulebinh/auto_avsr_av_trlrwlrs2lrs3vox2avsp_base", "AV model weights (whisper mode, 1.8 GB)"),
    ("models/qwen3-0.6b-4bit-mlx/config.json", "mlx-community/Qwen3-0.6B-4bit", "Qwen3-0.6B MLX config"),
    ("models/qwen3-0.6b-4bit-mlx/model.safetensors", "mlx-community/Qwen3-0.6B-4bit", "Qwen3-0.6B 4-bit MLX weights"),
    ("models/qwen3-0.6b-4bit-mlx/tokenizer.json", "mlx-community/Qwen3-0.6B-4bit", "Qwen3 tokenizer"),
    ("models/qwen3-0.6b-4bit-mlx/tokenizer_config.json", "mlx-community/Qwen3-0.6B-4bit", "Qwen3 tokenizer config"),
    ("models/qwen3-1.7b-4bit-mlx/config.json", "mlx-community/Qwen3-1.7B-4bit", "Qwen3-1.7B MLX config"),
    ("models/qwen3-1.7b-4bit-mlx/model.safetensors", "mlx-community/Qwen3-1.7B-4bit", "Qwen3-1.7B 4-bit MLX weights"),
    ("models/avhubert/model.pt", "vumichien/AV-HuBERT", "AV-HuBERT Large weights (backup only)"),
]


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    rows = []
    total = 0
    for rel, repo, desc in CATALOG:
        p = os.path.join(ROOT, rel)
        if os.path.exists(p):
            size = os.path.getsize(p)
            total += size
            rows.append((rel, repo, desc, f"{size / 1e6:.1f} MB", sha256(p)[:16] + "…"))
        else:
            rows.append((rel, repo, desc, "MISSING", "—"))
    # Any extra files in models/ not in the catalog?
    for dirpath, _dirs, files in os.walk(MODELS):
        for fn in files:
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, ROOT)
            if rel not in {r[0] for r in rows} and not fn.endswith(".part"):
                size = os.path.getsize(full)
                rows.append((rel, "(extra file in models/)", "", f"{size / 1e6:.1f} MB", sha256(full)[:16] + "…"))
    lines = ["# MODELS.md — inventory (generated, do not hand-edit)",
             "",
             "Generated by `python3 scripts/model_inventory.py` from the actual",
             "files in `models/`. Sizes are bytes on disk; SHA is sha256 (first 16 hex).",
             "If a file is MISSING, run `bash scripts/download-models.sh` (resumable).",
             "",
             "| File | Source (HF repo id) | What it is | Size | SHA256 |",
             "|---|---|---|---|---|"]
    for rel, repo, desc, size, sha in rows:
        lines.append(f"| `{rel}` | {repo} | {desc} | {size} | `{sha}` |")
    lines += ["", f"**Total on disk (catalogued files present): {total / 1e9:.2f} GB**", ""]
    out = os.path.join(ROOT, "MODELS.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {out} ({total / 1e9:.2f} GB present)")
    for r in rows:
        print(f"  {r[3]:>12}  {r[0]}")


if __name__ == "__main__":
    main()
